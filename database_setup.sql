-- Run this in SQL Developer as SYSTEM, connected to service FREEPDB1.
-- Assumes INCIDENTS, INCIDENT_AUDIT and UPDATE_INCIDENT_STATUS already exist.
GRANT SELECT, INSERT, UPDATE, DELETE ON SYSTEM.INCIDENTS TO INCIDENT_USER;
GRANT SELECT, INSERT, UPDATE, DELETE ON SYSTEM.INCIDENT_AUDIT TO INCIDENT_USER;
GRANT EXECUTE ON SYSTEM.UPDATE_INCIDENT_STATUS TO INCIDENT_USER;

CREATE OR REPLACE TRIGGER SYSTEM.TRG_INCIDENT_STATUS_AUDIT
AFTER UPDATE OF STATUS ON SYSTEM.INCIDENTS
FOR EACH ROW
WHEN (OLD.STATUS <> NEW.STATUS)
BEGIN
    INSERT INTO SYSTEM.INCIDENT_AUDIT (INCIDENT_ID, ACTION, DETAILS)
    VALUES (:NEW.INCIDENT_ID, 'STATUS UPDATE',
            'Status changed from ' || :OLD.STATUS || ' to ' || :NEW.STATUS);
END;
/
